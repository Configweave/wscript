//! `.wscripti` interface generation (PRD §9.1): dump every registered
//! module / function / type / const signature as a textual, human-readable,
//! diff-friendly subset of wscript syntax — declarations only, no bodies.
//! The same parser parses it; the LSP and `wscript check` consume it.

use std::fmt::Write;

use wscript_core::defs::{DefId, DefKind, FIRST_FREE_DEF, VariantKind};
use wscript_core::registry::{Registry, positional_param_name};
use wscript_core::types::{FnSig, Type};

pub fn render(reg: &Registry) -> String {
    let mut out = String::new();
    let _ = writeln!(
        out,
        "// Generated by wscript {} — host interface declarations.\n\
         // Consumed by the LSP and `wscript check` (list this file in wscript.toml).\n\
         // Do not edit by hand.",
        env!("CARGO_PKG_VERSION")
    );

    // Ambient types first (they belong to no namespace; modules may list
    // them, but the declarations live at the top level).
    for (i, def) in reg.defs.defs.iter().enumerate() {
        if (i as u32) < FIRST_FREE_DEF {
            continue;
        }
        let id = DefId(i as u32);
        match def {
            DefKind::Struct(s) if s.host => {
                out.push('\n');
                if s.opaque {
                    let _ = writeln!(out, "#[opaque]\nstruct {} {{}}", s.name);
                } else {
                    let _ = writeln!(out, "struct {} {{", s.name);
                    for (fname, fty) in &s.fields {
                        let _ = writeln!(out, "    {fname}: {},", fty.display(&reg.defs));
                    }
                    let _ = writeln!(out, "}}");
                }
                // Methods (PRD §6.2) render as an impl block of bodyless fns.
                if let Some(methods) = reg.methods.get(&id) {
                    let _ = writeln!(out, "\nimpl {} {{", s.name);
                    for m in methods {
                        if let Some(doc) = &m.doc {
                            for line in doc.lines() {
                                let _ = writeln!(out, "    /// {line}");
                            }
                        }
                        let _ = writeln!(
                            out,
                            "    fn {}({}){}",
                            m.name,
                            sig_params(&m.sig, m.param_names(), reg, true),
                            ret_suffix(&m.sig.ret, reg)
                        );
                    }
                    let _ = writeln!(out, "}}");
                }
            }
            DefKind::Enum(e) if e.host => {
                out.push('\n');
                let _ = writeln!(out, "enum {} {{", e.name);
                for v in &e.variants {
                    match v.kind {
                        VariantKind::Unit => {
                            let _ = writeln!(out, "    {},", v.name);
                        }
                        VariantKind::Tuple => {
                            let tys: Vec<String> =
                                v.fields.iter().map(|(_, t)| t.display(&reg.defs)).collect();
                            let _ = writeln!(out, "    {}({}),", v.name, tys.join(", "));
                        }
                        VariantKind::Struct => {
                            let fields: Vec<String> = v
                                .fields
                                .iter()
                                .map(|(n, t)| format!("{n}: {}", t.display(&reg.defs)))
                                .collect();
                            let _ = writeln!(out, "    {} {{ {} }},", v.name, fields.join(", "));
                        }
                    }
                }
                let _ = writeln!(out, "}}");
                if let Some(methods) = reg.methods.get(&id) {
                    let _ = writeln!(out, "\nimpl {} {{", e.name);
                    for m in methods {
                        if let Some(doc) = &m.doc {
                            for line in doc.lines() {
                                let _ = writeln!(out, "    /// {line}");
                            }
                        }
                        let _ = writeln!(
                            out,
                            "    fn {}({}){}",
                            m.name,
                            sig_params(&m.sig, m.param_names(), reg, true),
                            ret_suffix(&m.sig.ret, reg)
                        );
                    }
                    let _ = writeln!(out, "}}");
                }
            }
            _ => {}
        }
    }

    for module in &reg.modules {
        out.push('\n');
        if let Some(doc) = &module.doc {
            for line in doc.lines() {
                let _ = writeln!(out, "/// {line}");
            }
        }
        let _ = writeln!(out, "mod {} {{", module.name);
        for (name, ty, value) in &module.consts {
            let shown = match value {
                wscript_core::bytecode::Const::Int(n) => format!(" // = {n}"),
                wscript_core::bytecode::Const::Float(f) => format!(" // = {f}"),
                wscript_core::bytecode::Const::Bool(b) => format!(" // = {b}"),
                wscript_core::bytecode::Const::Char(c) => format!(" // = {c:?}"),
                wscript_core::bytecode::Const::Str(s) => format!(" // = {s:?}"),
                wscript_core::bytecode::Const::Unit => String::new(),
            };
            let _ = writeln!(out, "    const {name}: {}{shown}", ty.display(&reg.defs));
        }
        for f in &module.fns {
            if let Some(doc) = &f.doc {
                for line in doc.lines() {
                    let _ = writeln!(out, "    /// {line}");
                }
            }
            let _ = writeln!(
                out,
                "    fn {}({}){}",
                f.name,
                sig_params(&f.sig, f.param_names(), reg, false),
                ret_suffix(&f.sig.ret, reg)
            );
        }
        let _ = writeln!(out, "}}");
    }
    out
}

/// Render a parameter list. Declared names are emitted as written; where
/// the host declared none the positional placeholder stands in, because
/// the grammar requires a name and inventing a plausible one would hide
/// that nothing was ever declared.
fn sig_params(sig: &FnSig, names: Option<&[String]>, reg: &Registry, method: bool) -> String {
    let mut parts: Vec<String> = Vec::new();
    if method {
        parts.push("self".into());
    }
    for (i, p) in sig.params.iter().enumerate() {
        let name = names
            .and_then(|names| names.get(i))
            .cloned()
            .unwrap_or_else(|| positional_param_name(i));
        parts.push(format!("{name}: {}", p.display(&reg.defs)));
    }
    parts.join(", ")
}

fn ret_suffix(ret: &Type, reg: &Registry) -> String {
    if *ret == Type::Unit {
        String::new()
    } else {
        format!(" -> {}", ret.display(&reg.defs))
    }
}
